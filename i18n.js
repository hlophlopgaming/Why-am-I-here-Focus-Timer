 function t(text, language = "en") {
  const dictionary = translations[language];
  if (!dictionary) return text;
  if (Object.hasOwn(dictionary, text)) return dictionary[text];
  const prefix = Object.keys(dictionary).find(key => key.endsWith(": ") && text.startsWith(key));
  return prefix ? dictionary[prefix] + t(text.slice(prefix.length), language) : text;
 }
